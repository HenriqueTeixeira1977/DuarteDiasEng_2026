          <p>Contratar um serviço de pintura ou restauração de fachada envolve, necessariamente, trabalho em altura. E isso não é um detalhe menor: o síndico que contrata uma empresa sem as certificações corretas assume um risco real — tanto para a segurança dos trabalhadores quanto para a responsabilidade jurídica do condomínio em caso de acidente.</p>

          <h2>O que é a NR-35</h2>
          <p>A Norma Regulamentadora 35 (NR-35) é a legislação brasileira que estabelece os requisitos mínimos para o trabalho em altura — considerado qualquer atividade executada acima de 2 metros do nível inferior, com risco de queda. Ela define treinamento obrigatório, uso de equipamentos de proteção individual (EPIs) específicos, procedimentos de segurança e avaliação médica dos trabalhadores.</p>

          <h2>Por que isso importa para o condomínio, não só para a empresa</h2>
          <p>Muitos síndicos acreditam que a responsabilidade de segurança do trabalho é só da empresa contratada. Mas, em caso de acidente por negligência comprovada na contratação (por exemplo, contratar uma empresa sem qualquer certificação, visivelmente sem estrutura), o condomínio também pode ser corresponsabilizado civilmente. Por isso, verificar a conformidade da empresa não é burocracia — é proteção para o próprio condomínio.</p>

          <h2>O que exigir antes de fechar contrato</h2>
          <ul>
            <li><strong>Certificado de treinamento NR-35</strong> de todos os profissionais que vão trabalhar em altura, com validade dentro do prazo (o treinamento tem validade de 2 anos);</li>
            <li><strong>ASO (Atestado de Saúde Ocupacional)</strong> específico para trabalho em altura, comprovando aptidão física dos profissionais;</li>
            <li><strong>Equipamentos de Proteção Individual (EPIs)</strong> com certificado de aprovação (CA) — cadeirinhas, capacetes, cordas, trava-quedas;</li>
            <li><strong>Seguro de responsabilidade civil</strong> da empresa contratada;</li>
            <li><strong>ART (Anotação de Responsabilidade Técnica)</strong> do responsável técnico do projeto, registrada no CREA.</li>
          </ul>

          <blockquote>Peça sempre para ver os documentos antes de assinar o contrato — uma empresa séria não tem problema nenhum em apresentar essas certificações.</blockquote>

          <h2>Sinais de alerta ao contratar</h2>
          <p>Desconfie de empresas que não conseguem apresentar a documentação com facilidade, que usam equipamentos visivelmente desgastados ou improvisados, ou que oferecem preços muito abaixo do mercado — muitas vezes isso significa corte de custos justamente na segurança da equipe.</p>

